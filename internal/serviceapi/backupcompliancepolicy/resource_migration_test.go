// Migration tests for the autogenerated mongodbatlas_backup_compliance_policy (syntax rewrite + SDKv2 group):
// step 1 applies the manual block syntax (policy_item_hourly/... and on_demand_policy_item blocks) with the
// released provider, the next steps use the API's scheduled_policy_items list and assignment syntax that the
// autogen implementation requires, with the same values. The first plan after the switch (with refresh) must be
// EMPTY at the same address, an update must keep the crafted id, and the final plan must converge.

const (
	migResourceName = "mongodbatlas_backup_compliance_policy.test"
)

// TestMigBackupCompliancePolicy_basic covers every frequency (including yearly) and the on-demand policy item,
// the SDKv2 list-of-one shapes that must decode into the autogen object/list attributes.
func TestMigBackupCompliancePolicy_basic(t *testing.T) {
	var (
		orgID          = os.Getenv("MONGODB_ATLAS_ORG_ID")
		projectName    = acc.RandomProjectName() // No ProjectIDExecution to avoid conflicts with backup compliance policy
		projectOwnerID = os.Getenv("MONGODB_ATLAS_PROJECT_OWNER_ID")
	)
	migTestCase(t,
		configBasicBlocks(projectName, orgID, projectOwnerID),
		configBasic(projectName, orgID, projectOwnerID),
		configBasicUpdate(projectName, orgID, projectOwnerID),
	)
}

