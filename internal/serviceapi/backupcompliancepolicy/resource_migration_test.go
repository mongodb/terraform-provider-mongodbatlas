func migTestCase(t *testing.T, configBlocks, config, configUpdate string) {
	t.Helper()
	sameID := statecheck.CompareValue(compare.ValuesSame())
	// AddStateValue registers one value per call, so each step needs its own check.
	stateChecks := func() []statecheck.StateCheck {
		return []statecheck.StateCheck{sameID.AddStateValue(migResourceName, tfjsonpath.New("id"))}
	}
	checks := checkExists(migResourceName)

	resource.ParallelTest(t, resource.TestCase{
		PreCheck:     func() { mig.PreCheckBasic(t) },
		CheckDestroy: checkDestroy,
		Steps: []resource.TestStep{
			{
				// Step 1: the released provider (manual SDKv2 implementation) enables the policy with block syntax.
				ExternalProviders: mig.ExternalProviders(),
				Config:            configBlocks,
				Check:             resource.ComposeAggregateTestCheckFunc(checks),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 2: the autogen implementation plans the new structure with no diff at the same address.
				Config:                   config,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
				},
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 3: an in-place update with autogen keeps the crafted id.
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				Check:                    resource.ComposeAggregateTestCheckFunc(checks),
				ConfigStateChecks:        stateChecks(),
			},
			{
				// Step 4: convergence, a diff here would be a perpetual diff (parity gap).
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
		},
	})
}

func checkExists(resourceName string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("not found: %s", resourceName)
		}
		if rs.Primary.ID == "" {
			return fmt.Errorf("no ID is set")
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		policy, _, err := acc.ConnV2().CloudBackupsAPI.GetCompliancePolicy(context.Background(), ids["project_id"]).Execute()
		if err != nil || policy == nil {
			return fmt.Errorf("backup compliance policy (%s) does not exist: %s", rs.Primary.ID, err)
		}
		return nil
	}
}

func checkDestroy(s *terraform.State) error {
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "mongodbatlas_backup_compliance_policy" {
			continue
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		policy, _, err := acc.ConnV2().CloudBackupsAPI.GetCompliancePolicy(context.Background(), ids["project_id"]).Execute()
		if err == nil && policy.GetState() != "DISABLING" {
			return fmt.Errorf("backup compliance policy (project %s) still exists with state %s", ids["project_id"], policy.GetState())
		}
	}
	return nil
}

