// Migration tests for the autogenerated mongodbatlas_api_key_project_assignment: the config is
// identical under the manual and autogen implementations, so the migration must plan EMPTY at the
// same address. The identity (project_id/api_key_id) must survive the switch and later updates.

const migResourceName = "mongodbatlas_api_key_project_assignment.test"

func TestMigAPIKeyProjectAssignment_basic(t *testing.T) {
	migTestCase(t, []string{"GROUP_OWNER"})
}

// TestMigAPIKeyProjectAssignment_multipleRoles covers set semantics: the read returns the roles as
// objects in API order, and the hook keeps only this project's role names.
func TestMigAPIKeyProjectAssignment_multipleRoles(t *testing.T) {
	migTestCase(t, []string{"GROUP_OWNER", "GROUP_READ_ONLY"})
}

func migTestCase(t *testing.T, roles []string) {
	t.Helper()
	var (
		orgID         = os.Getenv("MONGODB_ATLAS_ORG_ID")
		projectName   = acc.RandomProjectName()
		config        = migConfig(orgID, projectName, roles)
		configUpdate  = migConfig(orgID, projectName, []string{"GROUP_READ_ONLY"})
		sameProjectID = statecheck.CompareValue(compare.ValuesSame())
		sameAPIKeyID  = statecheck.CompareValue(compare.ValuesSame())
	)
	// AddStateValue registers one value per call, so each step needs its own checks.
	stateChecks := func() []statecheck.StateCheck {
		return []statecheck.StateCheck{
			sameProjectID.AddStateValue(migResourceName, tfjsonpath.New("project_id")),
			sameAPIKeyID.AddStateValue(migResourceName, tfjsonpath.New("api_key_id")),
		}
	}

	resource.ParallelTest(t, resource.TestCase{
		PreCheck:     func() { mig.PreCheckBasic(t) },
		CheckDestroy: checkDestroy,
		Steps: []resource.TestStep{
			{
				// Step 1: the released provider (manual implementation) creates the assignment.
				ExternalProviders: mig.ExternalProviders(),
				Config:            config,
				Check:             checkAssignment(roles),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 2: the autogen implementation must plan no diff at the same address.
				Config:                   config,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
			{
				// Step 3: an in-place update with autogen keeps the identity.
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				Check:                    checkAssignment([]string{"GROUP_READ_ONLY"}),
				ConfigStateChecks:        stateChecks(),
			},
			{
				// Step 4: convergence, a diff here would be a perpetual diff (parity gap).
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
		},
	})
}

func checkAssignment(roles []string) resource.TestCheckFunc {
	return resource.ComposeAggregateTestCheckFunc(
		checkExists(migResourceName),
		resource.TestCheckResourceAttr(migResourceName, "roles.#", fmt.Sprintf("%d", len(roles))),
	)
}

func migConfig(orgID, projectName string, roles []string) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_project" "test" {
			name   = %[2]q
			org_id = %[1]q
		}

		resource "mongodbatlas_api_key" "test" {
			org_id      = %[1]q
			description = "api key project assignment migration test"
			role_names  = ["ORG_READ_ONLY"]
		}

		resource "mongodbatlas_api_key_project_assignment" "test" {
			project_id = mongodbatlas_project.test.id
			api_key_id = mongodbatlas_api_key.test.api_key_id
			roles      = ["%[3]s"]
		}
	`, orgID, projectName, strings.Join(roles, `", "`))
}

func checkExists(resourceName string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("not found: %s", resourceName)
		}
		projectID := rs.Primary.Attributes["project_id"]
		apiKeyID := rs.Primary.Attributes["api_key_id"]
		apiKeys, _, err := acc.ConnV2().ProgrammaticAPIKeysAPI.ListGroupApiKeys(context.Background(), projectID).Execute()
		if err != nil {
			return fmt.Errorf("error fetching project API keys: %w", err)
		}
		for _, apiKey := range apiKeys.GetResults() {
			if apiKey.GetId() == apiKeyID {
				return nil
			}
		}
		return fmt.Errorf("API key (%s) is not assigned to project (%s)", apiKeyID, projectID)
	}
}

func checkDestroy(s *terraform.State) error {
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "mongodbatlas_api_key_project_assignment" {
			continue
		}
		projectID := rs.Primary.Attributes["project_id"]
		apiKeyID := rs.Primary.Attributes["api_key_id"]
		apiKeys, apiResp, err := acc.ConnV2().ProgrammaticAPIKeysAPI.ListGroupApiKeys(context.Background(), projectID).Execute()
		if err != nil {
			if validate.StatusNotFound(apiResp) {
				return nil // the project is gone, so the assignment is gone too
			}
			return fmt.Errorf("error fetching project API keys: %w", err)
		}
		for _, apiKey := range apiKeys.GetResults() {
			if apiKey.GetId() == apiKeyID {
				return fmt.Errorf("API key (%s) is still assigned to project (%s)", apiKeyID, projectID)
			}
		}
	}
	return nil
}
