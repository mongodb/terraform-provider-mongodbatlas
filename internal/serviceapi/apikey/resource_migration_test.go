// Migration tests for the autogenerated mongodbatlas_api_key (SDKv2, no syntax rewrite group): the
// config is identical under the manual and autogen implementations, so the migration must plan
// EMPTY at the same address. The private key is only returned on create, so it must survive the
// switch and later updates unchanged, as must the crafted id.

const migResourceName = "mongodbatlas_api_key.test"

func TestMigAPIKey_basic(t *testing.T) {
	migTestCase(t, []string{"ORG_MEMBER"})
}

// TestMigAPIKey_multipleRoles covers set semantics of role_names (API order may differ from config order).
func TestMigAPIKey_multipleRoles(t *testing.T) {
	migTestCase(t, []string{"ORG_READ_ONLY", "ORG_BILLING_ADMIN", "ORG_MEMBER"})
}

func migTestCase(t *testing.T, roleNames []string) {
	t.Helper()
	var (
		orgID             = os.Getenv("MONGODB_ATLAS_ORG_ID")
		description       = acc.RandomName()
		descriptionUpdate = description + "-updated"
		config            = migConfig(orgID, description, roleNames)
		configUpdate      = migConfig(orgID, descriptionUpdate, roleNames)
		samePrivateKey    = statecheck.CompareValue(compare.ValuesSame())
		sameID            = statecheck.CompareValue(compare.ValuesSame())
	)
	// AddStateValue registers one value per call, so each step needs its own checks.
	stateChecks := func() []statecheck.StateCheck {
		return []statecheck.StateCheck{
			samePrivateKey.AddStateValue(migResourceName, tfjsonpath.New("private_key")),
			sameID.AddStateValue(migResourceName, tfjsonpath.New("id")),
		}
	}

	resource.ParallelTest(t, resource.TestCase{
		PreCheck:     func() { mig.PreCheckBasic(t) },
		CheckDestroy: checkDestroy,
		Steps: []resource.TestStep{
			{
				// Step 1: the released provider (manual SDKv2 implementation) creates the API key.
				ExternalProviders: mig.ExternalProviders(),
				Config:            config,
				Check: resource.ComposeAggregateTestCheckFunc(
					checkExists(migResourceName),
					resource.TestCheckResourceAttr(migResourceName, "org_id", orgID),
					resource.TestCheckResourceAttr(migResourceName, "description", description),
					resource.TestCheckResourceAttr(migResourceName, "role_names.#", fmt.Sprintf("%d", len(roleNames))),
					resource.TestCheckResourceAttrSet(migResourceName, "private_key"),
				),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 2: the autogen implementation must plan no diff at the same address.
				Config:                   config,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
			{
				// Step 3: an in-place update with autogen keeps the identity and the create-only private key.
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				Check: resource.ComposeAggregateTestCheckFunc(
					checkExists(migResourceName),
					resource.TestCheckResourceAttr(migResourceName, "description", descriptionUpdate),
					resource.TestCheckResourceAttr(migResourceName, "role_names.#", fmt.Sprintf("%d", len(roleNames))),
				),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 4: convergence, a diff here would be a perpetual diff (parity gap).
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
		},
	})
}

func migConfig(orgID, description string, roleNames []string) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_api_key" "test" {
			org_id      = %[1]q
			description = %[2]q
			role_names  = ["%[3]s"]
		}
	`, orgID, description, strings.Join(roleNames, `", "`))
}

func checkExists(resourceName string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("not found: %s", resourceName)
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		if ids["org_id"] != rs.Primary.Attributes["org_id"] || ids["api_key_id"] != rs.Primary.Attributes["api_key_id"] {
			return fmt.Errorf("id %q does not encode org_id and api_key_id", rs.Primary.ID)
		}
		_, _, err := acc.ConnV2().ProgrammaticAPIKeysAPI.GetOrgApiKey(context.Background(), ids["org_id"], ids["api_key_id"]).Execute()
		return err
	}
}

func checkDestroy(s *terraform.State) error {
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "mongodbatlas_api_key" {
			continue
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		_, _, err := acc.ConnV2().ProgrammaticAPIKeysAPI.GetOrgApiKey(context.Background(), ids["org_id"], ids["api_key_id"]).Execute()
		if err == nil {
			return fmt.Errorf("API Key (%s) still exists", ids["api_key_id"])
		}
	}
	return nil
}
