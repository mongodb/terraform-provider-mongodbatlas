// Migration tests for the autogenerated mongodbatlas_alert_configuration (BL1 syntax rewrite group): step 1
// applies the block syntax with the released provider (manual implementation), the next steps use the
// assignment syntax the autogen implementation requires, with the same values. The first plan after the
// switch must be EMPTY at the same address, an update must keep the id, and the final plan must converge.

const (
	migResourceName = "mongodbatlas_alert_configuration.test"
)

// TestMigAlertConfiguration_basic covers several notifications, a matcher and metric_threshold_config
// (a block in the manual resource, a single nested attribute in the autogen schema).
func TestMigAlertConfiguration_basic(t *testing.T) {
	var (
		projectID = acc.ProjectIDExecution(t)
	)
	migTestCase(t,
		migConfigBasicBlocks(projectID, true, 5, 99.0),
		migConfigBasic(projectID, true, 5, 99.0),
		migConfigBasic(projectID, true, 10, 89.7),
	)
}

// TestMigAlertConfiguration_minimal covers the empty-collection case: no matcher and no threshold block
// (the manual resource sent an empty matchers array). The legacy {project_id}-{alert_configuration_id}
// import format is covered by the manual suite's import steps (importStateProjectIDFunc).
func TestMigAlertConfiguration_minimal(t *testing.T) {
	var (
		projectID = acc.ProjectIDExecution(t)
	)
	migTestCase(t,
		migConfigMinimalBlocks(projectID, true, 5),
		migConfigMinimal(projectID, true, 5),
		migConfigMinimal(projectID, false, 10),
	)
}

func migTestCase(t *testing.T, configBlocks, config, configUpdate string) {
	t.Helper()
	sameID := statecheck.CompareValue(compare.ValuesSame())
	// AddStateValue registers one value per call, so each step needs its own checks.
	stateChecks := func() []statecheck.StateCheck {
		return []statecheck.StateCheck{sameID.AddStateValue(migResourceName, tfjsonpath.New("id"))}
	}
	checks := resource.ComposeAggregateTestCheckFunc(checkExists(migResourceName))

	resource.ParallelTest(t, resource.TestCase{
		PreCheck:     func() { mig.PreCheckBasic(t) },
		CheckDestroy: checkDestroy,
		Steps: []resource.TestStep{
			{
				// Step 1: the released provider (manual implementation) creates the alert configuration with block syntax.
				ExternalProviders: mig.ExternalProviders(),
				Config:            configBlocks,
				Check:             checks,
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 2: the first (refreshing) plan of the autogen implementation with the assignment syntax is
				// empty at the same address. The manual encoded id changes to the API id during this refresh.
				Config:                   config,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
				},
				Check: resource.ComposeAggregateTestCheckFunc(
					checks,
					resource.TestCheckResourceAttrPair(migResourceName, "id", migResourceName, "alert_configuration_id"),
				),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 3: an in-place update with autogen keeps the id.
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				Check:                    checks,
				ConfigStateChecks:        stateChecks(),
			},
			{
				// Step 4: convergence, a diff here would be a perpetual diff (parity gap).
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
		},
	})
}

func checkExists(resourceName string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("not found: %s", resourceName)
		}
		if rs.Primary.ID == "" {
			return fmt.Errorf("no ID is set")
		}
		projectID := rs.Primary.Attributes["project_id"]
		alertID := rs.Primary.Attributes["alert_configuration_id"]
		_, _, err := acc.ConnV2().AlertConfigurationsAPI.GetAlertConfig(context.Background(), projectID, alertID).Execute()
		if err != nil {
			return fmt.Errorf("the Alert Configuration(%s) does not exist", alertID)
		}
		return nil
	}
}

func checkDestroy(s *terraform.State) error {
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "mongodbatlas_alert_configuration" {
			continue
		}
		projectID := rs.Primary.Attributes["project_id"]
		alertID := rs.Primary.Attributes["alert_configuration_id"]
		alert, _, err := acc.ConnV2().AlertConfigurationsAPI.GetAlertConfig(context.Background(), projectID, alertID).Execute()
		if alert != nil {
			return fmt.Errorf("the Project Alert Configuration(%s) still exists %s", alertID, err)
		}
	}
	return nil
}

func migConfigBasicBlocks(projectID string, enabled bool, intervalMin int, threshold float64) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_alert_configuration" "test" {
			project_id = %[1]q
			enabled    = %[2]t
			event_type = "OUTSIDE_METRIC_THRESHOLD"

			notification {
				type_name     = "GROUP"
				interval_min  = %[3]d
				delay_min     = 0
				sms_enabled   = false
				email_enabled = true
				roles         = ["GROUP_DATA_ACCESS_READ_ONLY", "GROUP_CLUSTER_MANAGER"]
			}

			notification {
				type_name     = "ORG"
				interval_min  = %[3]d
				delay_min     = 0
				sms_enabled   = true
				email_enabled = false
			}

			matcher {
				field_name = "HOSTNAME_AND_PORT"
				operator   = "EQUALS"
				value      = "SECONDARY"
			}

			metric_threshold_config {
				metric_name = "ASSERT_REGULAR"
				operator    = "LESS_THAN"
				threshold   = %[4]g
				units       = "RAW"
				mode        = "AVERAGE"
			}
		}
	`, projectID, enabled, intervalMin, threshold)
}

