// Manual-parity custom code for mongodbatlas_alert_configuration (lift-and-shift from the handwritten
// Terraform Plugin Framework resource).

// TFExpandedModel adds the `id` attribute: the alert configuration id returned by the API. The manual
// resource stored an encoded {project_id, alert_configuration_id} id in `id` and the plain API id in the
// computed `alert_configuration_id`; the autogenerated resource uses the plain API id in both, so the
// API `id` property is unmarshaled natively into `id` (declared in the schema by the hook below).
type TFExpandedModel struct {
	ID types.String `tfsdk:"id" apiname:"id" autogen:"omitjson"`
}

var (
	_ autogen.PreCreateAPICallHook  = (*rs)(nil)
	_ autogen.PreUpdateAPICallHook  = (*rs)(nil)
	_ autogen.PostCreateAPICallHook = (*rs)(nil)
	_ autogen.PostReadAPICallHook   = (*rs)(nil)
	_ autogen.PostUpdateAPICallHook = (*rs)(nil)
	_ autogen.PreImportHook         = (*rs)(nil)
	_ autogen.ResourceSchemaHook    = (*rs)(nil)
	// Enables the state upgrade below for state written by the manual resource (schema version 0).
	_ resource.ResourceWithUpgradeState = (*rs)(nil)
)

func (r *rs) ResourceSchema(ctx context.Context, baseSchema schema.Schema) schema.Schema {
	// Version 1: triggers the state upgrade below for state written by the manual resource (version 0).
	baseSchema.Version = 1

	baseSchema.Attributes["id"] = schema.StringAttribute{
		Computed: true,
		PlanModifiers: []planmodifier.String{
			stringplanmodifier.UseStateForUnknown(),
		},
	}
	// The manual resource has UseStateForUnknown on alert_configuration_id.
	alertConfigurationID := baseSchema.Attributes["alert_configuration_id"].(schema.StringAttribute)
	alertConfigurationID.PlanModifiers = []planmodifier.String{stringplanmodifier.UseStateForUnknown()}
	baseSchema.Attributes["alert_configuration_id"] = alertConfigurationID

	// ForceNew in the manual resource: RequiresReplace instead of the generated CreateOnly.
	projectID := baseSchema.Attributes["project_id"].(schema.StringAttribute)
	projectID.PlanModifiers = []planmodifier.String{stringplanmodifier.RequiresReplace()}
	baseSchema.Attributes["project_id"] = projectID

	// Ported as-is from the manual resource schema.
	metricThreshold := baseSchema.Attributes["metric_threshold_config"].(schema.SingleNestedAttribute)
	metricThreshold.Attributes["operator"] = stringAttrWithValidators(
		metricThreshold.Attributes["operator"],
		stringvalidator.OneOf("GREATER_THAN", "LESS_THAN"),
	)
	baseSchema.Attributes["metric_threshold_config"] = metricThreshold

	threshold := baseSchema.Attributes["threshold_config"].(schema.SingleNestedAttribute)
	threshold.Attributes["units"] = stringAttrWithValidators(
		threshold.Attributes["units"],
		stringvalidator.OneOf(
			"RAW", "BITS", "BYTES", "KILOBITS", "KILOBYTES", "MEGABITS", "MEGABYTES",
			"GIGABITS", "GIGABYTES", "TERABYTES", "PETABYTES",
			"MILLISECONDS", "SECONDS", "MINUTES", "HOURS", "DAYS",
		),
	)
	baseSchema.Attributes["threshold_config"] = threshold

	notification := baseSchema.Attributes["notification"].(schema.ListNestedAttribute)
	notification.NestedObject.Attributes["type_name"] = stringAttrWithValidators(
		notification.NestedObject.Attributes["type_name"],
		stringvalidator.OneOf("EMAIL", "SMS", "PAGER_DUTY", "SLACK", "DATADOG", "OPS_GENIE", "VICTOR_OPS",
			"WEBHOOK", "USER", "TEAM", "GROUP", "ORG", "MICROSOFT_TEAMS"),
	)
	notification.NestedObject.Attributes["ops_genie_region"] = stringAttrWithValidators(
		notification.NestedObject.Attributes["ops_genie_region"],
		stringvalidator.OneOf("US", "EU"),
	)
	intervalMin := notification.NestedObject.Attributes["interval_min"].(schema.Int64Attribute)
	intervalMin.Validators = []validator.Int64{ValidIntervalMin()}
	notification.NestedObject.Attributes["interval_min"] = intervalMin
	baseSchema.Attributes["notification"] = notification

	return baseSchema
}

// stringAttrWithValidators returns the attribute as a StringAttribute with the given validators appended.
func stringAttrWithValidators(base schema.Attribute, validators ...validator.String) schema.StringAttribute {
	attr, ok := base.(schema.StringAttribute)
	if !ok {
		return schema.StringAttribute{}
	}
	attr.Validators = validators
	return attr
}

// PostCreateAPICall and PostUpdateAPICall normalize the response the same way the manual resource did
// (NewTFAlertConfigurationModel), so state matches what a manual read would have stored.
func (r *rs) PostCreateAPICall(result autogen.APICallResult) autogen.APICallResult {
	return applyThresholdPrecedence(normalizeAlertConfigResponse(result))
}

func (r *rs) PostUpdateAPICall(result autogen.APICallResult) autogen.APICallResult {
	return applyThresholdPrecedence(normalizeAlertConfigResponse(result))
}

// PreCreateAPICall and PreUpdateAPICall add the zero values the manual resource sent for unset
// attributes (see fillManualZeroValues), without which the API rejects the request.
func (r *rs) PreCreateAPICall(callParams config.APICallParams, bodyReq []byte) (modifiedParams config.APICallParams, modifiedBody []byte) {
	return fillManualZeroValues(callParams, bodyReq)
}

func (r *rs) PreUpdateAPICall(callParams config.APICallParams, bodyReq []byte) (modifiedParams config.APICallParams, modifiedBody []byte) {
	return fillManualZeroValues(callParams, bodyReq)
}

// UpgradeState upgrades state written by the manual resource (schema version 0) to the autogenerated
// schema (version 1). The structural change (BL1): the manual `metric_threshold_config` and
// `threshold_config` blocks (lists of at most one item) become single nested attributes (objects).
func (r *rs) UpgradeState(context.Context) map[int64]resource.StateUpgrader {
	return map[int64]resource.StateUpgrader{
		0: {StateUpgrader: upgradeManualStateV0},
	}
}

func upgradeManualStateV0(ctx context.Context, req resource.UpgradeStateRequest, resp *resource.UpgradeStateResponse) {
	fixedJSON, err := upgradeManualStateJSON(req.RawState.JSON)
	if err != nil {
		resp.Diagnostics.AddError("Unable to Read Previously Saved State for UpgradeResourceState", err.Error())
		return
	}
	rawStateValue, err := tftypes.ValueFromJSONWithOpts(fixedJSON, resp.State.Schema.Type().TerraformType(ctx), tftypes.ValueFromJSONOpts{
		IgnoreUndefinedAttributes: true,
	})
	if err != nil {
		resp.Diagnostics.AddError("Unable to Read Previously Saved State for UpgradeResourceState", err.Error())
		return
	}
	resp.State.Raw = rawStateValue
}

// upgradeManualStateJSON rewrites raw state written by the manual resource (schema version 0) into the
// shape the autogenerated schema expects (version 1).
func upgradeManualStateJSON(rawJSON []byte) ([]byte, error) {
	rawMap := map[string]any{}
	if err := json.Unmarshal(rawJSON, &rawMap); err != nil {
		return nil, err
	}
	for _, name := range []string{"metric_threshold_config", "threshold_config"} {
		unwrapListOfOne(rawMap, name)
	}
	return json.Marshal(rawMap)
}

// unwrapListOfOne converts the manual list-of-at-most-one block into the single nested attribute object:
// the item of a one-element list becomes the object; an empty or absent list is removed (null object).
func unwrapListOfOne(rawMap map[string]any, name string) {
	items, ok := rawMap[name].([]any)
	if !ok {
		return
	}
	if len(items) == 0 {
		delete(rawMap, name)
		return
	}
	if item, isMap := items[0].(map[string]any); isMap {
		rawMap[name] = item
	}
}

// fillManualZeroValues reproduces the request body the manual resource marshaled for unset attributes:
// Terraform plans optional+computed attributes as unknown on create, and the manual model's
// ValueXPointer() sent a zero value for unknown fields (pointer to 0, false or ""), while the generated
// marshal omits unknowns and the API rejects the request (MISSING_ATTRIBUTE for `threshold` and
// `intervalMin`). `delayMin` was always sent (pointer to 0 even when null), and the manual model sent
// `notifierId`/`integrationId` as "" when unset.
func fillManualZeroValues(callParams config.APICallParams, bodyReq []byte) (modifiedParams config.APICallParams, modifiedBody []byte) {
	if autogen.IsEmptyJSON(bodyReq) {
		return callParams, bodyReq
	}
	var obj map[string]any
	if err := autogen.Decode(bodyReq, &obj); err != nil {
		return callParams, bodyReq // leave the body untouched; the generated marshal owns it
	}
	for _, notification := range notificationsOf(obj) {
		setIfMissing(notification, "delayMin", 0)
		setIfMissing(notification, "intervalMin", 0)
		setIfMissing(notification, "smsEnabled", false)
		setIfMissing(notification, "emailEnabled", false)
		setIfMissing(notification, "notifierId", "")
		setIfMissing(notification, "integrationId", "")
	}
	for _, name := range []string{"metricThreshold", "threshold"} {
		if threshold, ok := obj[name].(map[string]any); ok {
			setIfMissing(threshold, "threshold", 0)
		}
	}
	setIfMissing(obj, "enabled", false)
	body, err := json.Marshal(obj)
	if err != nil {
		return callParams, bodyReq
	}
	return callParams, body
}

func notificationsOf(obj map[string]any) []map[string]any {
	items, ok := obj["notifications"].([]any)
	if !ok {
		return nil
	}
	result := make([]map[string]any, 0, len(items))
	for _, item := range items {
		if notification, ok := item.(map[string]any); ok {
			result = append(result, notification)
		}
	}
	return result
}

func setIfMissing(obj map[string]any, key string, value any) {
	if _, ok := obj[key]; !ok {
		obj[key] = value
	}
}

// PostReadAPICall applies the same adaptations; the threshold precedence matters here for
// OUTSIDE_STREAM_PROCESSOR_METRIC_THRESHOLD, for which the API returns both `metricThreshold` and
// `threshold` for backwards compatibility (HELP-91242): the manual read keeps only
// `metric_threshold_config` to avoid an inconsistent state.
func (r *rs) PostReadAPICall(req autogen.HandleReadReq, result autogen.APICallResult) autogen.APICallResult {
	return applyThresholdPrecedence(normalizeAlertConfigResponse(result))
}

func (r *rs) PreImport(id string) (string, error) {
	// The manual import format is {project_id}-{alert_configuration_id}; both parts are 24-hex strings
	// without dashes, so the rewrite is unambiguous.
	return replaceLegacyImport(id), nil
}

// replaceLegacyImport rewrites the manual {project_id}-{alert_configuration_id} format into the
// autogenerated {project_id}/{alert_configuration_id}; ids without a dash pass through unchanged.
func replaceLegacyImport(id string) string {
	for i := 0; i < len(id); i++ {
		if id[i] == '-' {
			return id[:i] + "/" + id[i+1:]
		}
	}
	return id
}

// applyThresholdPrecedence keeps `metricThreshold` and drops `threshold` from the response body when both
// are present, and vice versa, mirroring the manual newTFThresholdModels.
func applyThresholdPrecedence(result autogen.APICallResult) autogen.APICallResult {
	obj, ok := decodeBodyMap(result)
	if !ok {
		return result
	}
	changed := false
	switch {
	case hasObject(obj["metricThreshold"]):
		if _, ok := obj["threshold"]; ok {
			delete(obj, "threshold")
			changed = true
		}
	case hasObject(obj["threshold"]):
		if _, ok := obj["metricThreshold"]; ok {
			delete(obj, "metricThreshold")
			changed = true
		}
	}
	if !changed {
		return result
	}
	body, err := json.Marshal(obj)
	if err != nil {
		result.Err = err
		return result
	}
	result.Body = body
	return result
}

// normalizeAlertConfigResponse adapts the response notifications the way the manual resource did
// (NewTFNotificationModelList): sensitive attributes never take the value returned by the API (it is
// redacted, or echoed from a third-party integration), and empty strings are converted to null
// (conversion.StringPtrNullIfEmpty) so an unset notification attribute stays null in state.
func normalizeAlertConfigResponse(result autogen.APICallResult) autogen.APICallResult {
	obj, ok := decodeBodyMap(result)
	if !ok {
		return result
	}
	notifications, ok := obj["notifications"].([]any)
	if !ok {
		return result
	}
	changed := false
	for _, n := range notifications {
		notification, ok := n.(map[string]any)
		if !ok {
			continue
		}
		for _, key := range sensitiveNotificationKeys {
			if _, ok := notification[key]; ok {
				delete(notification, key)
				changed = true
			}
		}
		for _, key := range emptyToNullNotificationKeys {
			if value, ok := notification[key].(string); ok && value == "" {
				delete(notification, key)
				changed = true
			}
		}
	}
	if !changed {
		return result
	}
	body, err := json.Marshal(obj)
	if err != nil {
		result.Err = err
		return result
	}
	result.Body = body
	return result
}

// emptyToNullNotificationKeys are the non-sensitive notification string attributes the manual read
// normalizes with conversion.StringPtrNullIfEmpty.
var emptyToNullNotificationKeys = []string{
	"channelName", "datadogRegion", "emailAddress", "mobileNumber",
	"opsGenieRegion", "teamId", "teamName", "typeName", "username",
}

// sensitiveNotificationKeys are the notification attributes marked sensitive in the manual resource.
// They are always removed from the response body: autogen's unmarshal then keeps the value already set
// in state or plan (or null), replicating the manual behavior of never storing what the API returns for
// them. This avoids a plan-null to result-known inconsistency when the API echoes a credential stored in
// a third-party integration, and redacted values on read.
var sensitiveNotificationKeys = []string{
	"apiToken", "datadogApiKey", "opsGenieApiKey", "serviceKey",
	"victorOpsApiKey", "victorOpsRoutingKey", "webhookUrl", "webhookSecret",
	"webhookBodyTemplate", "webhookHeadersTemplate", "microsoftTeamsWebhookUrl",
}

func decodeBodyMap(result autogen.APICallResult) (map[string]any, bool) {
	if result.Err != nil || autogen.IsEmptyJSON(result.Body) {
		return nil, false
	}
	var obj map[string]any
	if err := autogen.Decode(result.Body, &obj); err != nil {
		return nil, false
	}
	return obj, true
}

func hasObject(value any) bool {
	_, ok := value.(map[string]any)
	return ok
}
