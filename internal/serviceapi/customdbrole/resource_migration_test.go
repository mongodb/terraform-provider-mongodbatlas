func checkExists(resourceName string) resource.TestCheckFunc {
	return func(s *terraform.State) error {
		rs, ok := s.RootModule().Resources[resourceName]
		if !ok {
			return fmt.Errorf("not found: %s", resourceName)
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		if ids["project_id"] != rs.Primary.Attributes["project_id"] || ids["role_name"] != rs.Primary.Attributes["role_name"] {
			return fmt.Errorf("id %q does not encode project_id and role_name", rs.Primary.ID)
		}
		_, _, err := acc.ConnV2().CustomDatabaseRolesAPI.GetCustomDbRole(context.Background(), ids["project_id"], ids["role_name"]).Execute()
		return err
	}
}

func checkDestroy(s *terraform.State) error {
	for _, rs := range s.RootModule().Resources {
		if rs.Type != "mongodbatlas_custom_db_role" {
			continue
		}
		ids := conversion.DecodeStateID(rs.Primary.ID)
		_, _, err := acc.ConnV2().CustomDatabaseRolesAPI.GetCustomDbRole(context.Background(), ids["project_id"], ids["role_name"]).Execute()
		if err == nil {
			return fmt.Errorf("custom DB role (%s) still exists", ids["role_name"])
		}
	}
	return nil
}
