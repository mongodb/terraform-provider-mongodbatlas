// Migration tests for the autogenerated mongodbatlas_custom_db_role (syntax rewrite + SDKv2 group): step 1 applies
// the block syntax with the released provider (manual SDKv2 implementation), the next steps use the assignment
// syntax the autogen implementation requires, with the same values. The first plan after the switch must be EMPTY at
// the same address, an update must keep the crafted id, and the final plan must converge.

const (
	migResourceName     = "mongodbatlas_custom_db_role.test"
	migBaseResourceName = "mongodbatlas_custom_db_role.base"
)

// TestMigCustomDBRole_basic covers a role without inherited_roles (SDKv2 stored the absent block as an empty set)
// and omitted optional resource fields.
func TestMigCustomDBRole_basic(t *testing.T) {
	var (
		projectID    = acc.ProjectIDExecution(t)
		roleName     = acc.RandomName()
		databaseName = acc.RandomClusterName()
	)
	migTestCase(t, []string{migResourceName},
		configBasicBlocks(projectID, roleName, "INSERT", databaseName),
		configBasic(projectID, roleName, "INSERT", databaseName),
		configBasic(projectID, roleName, "UPDATE", databaseName),
	)
}

// TestMigCustomDBRole_inheritedRoles covers inherited_roles, several actions and resources (set ordering) and a
// cluster resource.
func TestMigCustomDBRole_inheritedRoles(t *testing.T) {
	var (
		projectID     = acc.ProjectIDExecution(t)
		baseRoleName  = acc.RandomName()
		roleName      = acc.RandomName()
		databaseName1 = acc.RandomClusterName()
		databaseName2 = acc.RandomClusterName()
	)
	migTestCase(t, []string{migBaseResourceName, migResourceName},
		configInheritedBlocks(projectID, baseRoleName, roleName, databaseName1, databaseName2, "FIND"),
		configInherited(projectID, baseRoleName, roleName, databaseName1, databaseName2, "FIND"),
		configInherited(projectID, baseRoleName, roleName, databaseName1, databaseName2, "REMOVE"),
	)
}

func migTestCase(t *testing.T, resourceNames []string, configBlocks, config, configUpdate string) {
	t.Helper()
	sameIDs := make([]interface {
		AddStateValue(string, tfjsonpath.Path) statecheck.StateCheck
	}, len(resourceNames))
	for i := range resourceNames {
		sameIDs[i] = statecheck.CompareValue(compare.ValuesSame())
	}
	// AddStateValue registers one value per call, so each step needs its own checks.
	stateChecks := func() []statecheck.StateCheck {
		checks := make([]statecheck.StateCheck, len(resourceNames))
		for i, name := range resourceNames {
			checks[i] = sameIDs[i].AddStateValue(name, tfjsonpath.New("id"))
		}
		return checks
	}
	checks := func() resource.TestCheckFunc {
		fs := make([]resource.TestCheckFunc, len(resourceNames))
		for i, name := range resourceNames {
			fs[i] = checkExists(name)
		}
		return resource.ComposeAggregateTestCheckFunc(fs...)
	}

	resource.ParallelTest(t, resource.TestCase{
		PreCheck:     func() { mig.PreCheckBasic(t) },
		CheckDestroy: checkDestroy,
		Steps: []resource.TestStep{
			{
				// Step 1: the released provider (manual SDKv2 implementation) creates the roles with block syntax.
				ExternalProviders: mig.ExternalProviders(),
				Config:            configBlocks,
				Check:             checks(),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 2: the first (refreshing) plan of the autogen implementation with the assignment syntax is empty
				// at the same address. A PlanOnly step would fail on its non-refresh plan: SDKv2 left `cluster` null
				// on database resources, while autogen defaults it to false (set in state by the first refresh).
				Config:                   config,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				ConfigPlanChecks: resource.ConfigPlanChecks{
					PreApply: []plancheck.PlanCheck{plancheck.ExpectEmptyPlan()},
				},
				Check:             checks(),
				ConfigStateChecks: stateChecks(),
			},
			{
				// Step 3: an in-place update with autogen keeps the identity.
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				Check:                    checks(),
				ConfigStateChecks:        stateChecks(),
			},
			{
				// Step 4: convergence, a diff here would be a perpetual diff (parity gap).
				Config:                   configUpdate,
				ProtoV6ProviderFactories: acc.TestAccProviderV6Factories,
				PlanOnly:                 true,
				ExpectNonEmptyPlan:       false,
			},
		},
	})
}

func configBasicBlocks(projectID, roleName, action, databaseName string) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_custom_db_role" "test" {
			project_id = %[1]q
			role_name  = %[2]q

			actions {
				action = %[3]q
				resources {
					database_name = %[4]q
				}
			}
		}
	`, projectID, roleName, action, databaseName)
}

func configBasic(projectID, roleName, action, databaseName string) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_custom_db_role" "test" {
			project_id = %[1]q
			role_name  = %[2]q

			actions = [
				{
					action    = %[3]q
					resources = [{ database_name = %[4]q }]
				}
			]
		}
	`, projectID, roleName, action, databaseName)
}

func configInheritedBlocks(projectID, baseRoleName, roleName, databaseName1, databaseName2, action string) string {
	return fmt.Sprintf(`
		resource "mongodbatlas_custom_db_role" "base" {
			project_id = %[1]q
			role_name  = %[2]q

			actions {
				action = "SERVER_STATUS"
				resources {
					cluster = true
				}
			}
			actions {
				action = "INSERT"
				resources {
					collection_name = ""
					database_name   = %[4]q
				}
				resources {
					collection_name = "coll"
					database_name   = %[5]q
				}
			}
		}

		resource "mongodbatlas_custom_db_role" "test" {
			project_id = mongodbatlas_custom_db_role.base.project_id
			role_name  = %[3]q

			actions {
				action = %[6]q
				resources {
					collection_name = ""
					database_name   = %[4]q
				}
			}

			inherited_roles {
				role_name     = mongodbatlas_custom_db_role.base.role_name
				database_name = "admin"
			}
			inherited_roles {
				role_name     = "read"
				database_name = %[5]q
			}
		}
	`, projectID, baseRoleName, roleName, databaseName1, databaseName2, action)
}

