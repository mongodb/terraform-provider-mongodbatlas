// fixtureRepo creates a temp repo layout with a config.yml and some docs files:
//   - log_integration: resource doc + singular and plural data source docs
//   - mcp_config: resource doc only
//   - resource_policy_api: autogen but named _api, so no exact docs expected
//   - no_docs_resource(_with_ds): autogen without any docs files
//   - legacy_resource: doc that must NOT be considered autogenerated
func fixtureRepo(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	write := func(rel, content string) {
		writeFile(t, filepath.Join(root, rel), content)
	}
	write("tools/codegen/config.yml", fixtureConfig)
	write("docs/resources/log_integration.md", "log integration")
	write("docs/data-sources/log_integration.md", "log integration ds")
	write("docs/data-sources/log_integrations.md", "log integrations ds")
	write("docs/resources/mcp_config.md", "mcp config")
	write("docs/resources/legacy_resource.md", "legacy")
	return root
}

func TestAutogenDocsPaths(t *testing.T) {
	root := fixtureRepo(t)
	got, err := autogenDocsPaths(root)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"docs/data-sources/log_integration.md",
		"docs/data-sources/log_integrations.md",
		"docs/resources/log_integration.md",
		"docs/resources/mcp_config.md",
	}
	if len(got) != len(want) {
		t.Fatalf("got %v, want %v", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("got[%d] = %q, want %q", i, got[i], want[i])
		}
	}
}

func TestWriteFilters(t *testing.T) {
	root := fixtureRepo(t)
	dest := filepath.Join(root, "filters.yaml")
	if err := writeFilters(dest, mustPaths(t, root)); err != nil {
		t.Fatal(err)
	}
	content, err := os.ReadFile(dest)
	if err != nil {
		t.Fatal(err)
	}
	text := string(content)
	for _, want := range []string{
		"  - '.changelog/**'\n",
		"  - 'docs/**'\n",
		"  - '!docs/resources/log_integration.md'\n",
		"  - '!docs/data-sources/log_integrations.md'\n",
		"  - '!docs/resources/*_api.md'\n",
	} {
		if !strings.Contains(text, want) {
			t.Errorf("filters output missing %q, got:\n%s", want, text)
		}
	}
	if strings.Contains(text, "legacy_resource") {
		t.Errorf("filters output must not exclude legacy docs, got:\n%s", text)
	}
}

func TestCodeownersBlockAndCheck(t *testing.T) {
	root := fixtureRepo(t)
	block := codeownersBlockText(mustPaths(t, root))
	if !strings.HasPrefix(block, beginMarker+"\n") || !strings.HasSuffix(block, endMarker+"\n") {
		t.Fatalf("unexpected block:\n%s", block)
	}

	codeowners := "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n\n" + block
	if err := os.MkdirAll(filepath.Join(root, ".github"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, codeownersPath), []byte(codeowners), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := checkCodeowners(root); err != nil {
		t.Errorf("expected no drift, got error: %v", err)
	}

	// Simulate a new autogen resource with docs: check must detect drift.
	newConfig := strings.Replace(fixtureConfig, "  mcp_config:\n", "  mcp_config_new:\n    read:\n      path: /api/atlas/v2/mcpConfigsNew\n      method: GET\n  mcp_config:\n", 1)
	writeFile(t, filepath.Join(root, "tools", "codegen", "config.yml"), newConfig)
	writeFile(t, filepath.Join(root, "docs", "resources", "mcp_config_new.md"), "new autogen doc")
	if err := checkCodeowners(root); err == nil {
		t.Error("expected drift error after new autogenerated doc")
	}
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func mustPaths(t *testing.T, root string) []string {
	t.Helper()
	paths, err := autogenDocsPaths(root)
	if err != nil {
		t.Fatal(err)
	}
	return paths
}
