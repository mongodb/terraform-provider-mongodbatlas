func TestCodeownersBlockAndCheck(t *testing.T) {
	root := fixtureRepo(t)
	block := codeownersBlockText(mustPaths(t, root))
	if !strings.HasPrefix(block, beginMarker+"\n") || !strings.HasSuffix(block, endMarker+"\n") {
		t.Fatalf("unexpected block:\n%s", block)
	}

	codeowners := "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n\n" + block
	if err := os.MkdirAll(filepath.Join(root, ".github"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(root, codeownersPath), []byte(codeowners), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := checkCodeowners(root); err != nil {
		t.Errorf("expected no drift, got error: %v", err)
	}

	// A config change must detect drift before documentation is generated.
	newConfig := strings.Replace(fixtureConfig, "  mcp_config:\n", "  mcp_config_new:\n    read:\n      path: /api/atlas/v2/mcpConfigsNew\n      method: GET\n  mcp_config:\n", 1)
	writeFile(t, filepath.Join(root, "tools", "codegen", "config.yml"), newConfig)
	if err := checkCodeowners(root); err == nil {
		t.Error("expected drift error after new autogenerated doc")
	}
}

func TestUpdateCodeowners(t *testing.T) {
	t.Run("appends when the block is missing", func(t *testing.T) {
		root := fixtureRepo(t)
		writeFile(t, filepath.Join(root, codeownersPath), "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n")
		if err := updateCodeowners(root); err != nil {
			t.Fatal(err)
		}
		if err := checkCodeowners(root); err != nil {
			t.Errorf("expected no drift after update, got error: %v", err)
		}
		content, err := os.ReadFile(filepath.Join(root, codeownersPath))
		if err != nil {
			t.Fatal(err)
		}
		if !strings.HasPrefix(string(content), "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n\n") {
			t.Errorf("update must preserve existing CODEOWNERS content, got:\n%s", content)
		}
	})

	t.Run("replaces an existing outdated block in place", func(t *testing.T) {
		root := fixtureRepo(t)
		writeFile(t, filepath.Join(root, codeownersPath), "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n\n"+codeownersBlockText(mustPaths(t, root)))
		drifted := strings.Replace(fixtureConfig, "  mcp_config:\n", "  mcp_config_new:\n    read:\n      path: /api/atlas/v2/mcpConfigsNew\n      method: GET\n  mcp_config:\n", 1)
		writeFile(t, filepath.Join(root, "tools", "codegen", "config.yml"), drifted)
		if err := updateCodeowners(root); err != nil {
			t.Fatal(err)
		}
		if err := checkCodeowners(root); err != nil {
			t.Errorf("expected no drift after update, got error: %v", err)
		}
		content, err := os.ReadFile(filepath.Join(root, codeownersPath))
		if err != nil {
			t.Fatal(err)
		}
		if got := strings.Count(string(content), beginMarker); got != 1 {
			t.Errorf("expected exactly one block after update, got %d:\n%s", got, content)
		}
	})

	t.Run("is idempotent when content follows the block", func(t *testing.T) {
		root := fixtureRepo(t)
		writeFile(t, filepath.Join(root, codeownersPath), "# Maintained by the MongoDB APIx-Integrations team\n* @mongodb/APIx-Integrations\n\n"+codeownersBlockText(mustPaths(t, root))+"\n/some/rule @team\n")
		if err := updateCodeowners(root); err != nil {
			t.Fatal(err)
		}
		first, err := os.ReadFile(filepath.Join(root, codeownersPath))
		if err != nil {
			t.Fatal(err)
		}
		if err := checkCodeowners(root); err != nil {
			t.Errorf("expected no drift after update, got error: %v", err)
		}
		if err := updateCodeowners(root); err != nil {
			t.Fatal(err)
		}
		second, err := os.ReadFile(filepath.Join(root, codeownersPath))
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(first, second) {
			t.Errorf("second update changed the file:\nfirst:\n%s\nsecond:\n%s", first, second)
		}
		if !strings.Contains(string(first), "\n/some/rule @team\n") {
			t.Errorf("trailing content must be preserved, got:\n%s", first)
		}
		if strings.Count(string(first), "\n\n\n") > 0 {
			t.Errorf("update must not accumulate blank lines, got:\n%q", first)
		}
	})
}

func writeFile(t *testing.T, path, content string) {
	t.Helper()
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		t.Fatal(err)
	}
}

func mustPaths(t *testing.T, root string) []string {
	t.Helper()
	paths, err := autogenDocsPaths(root)
	if err != nil {
		t.Fatal(err)
	}
	return paths
}
